import Foundation

public enum PreviewState: String, Codable {
    case ready          // all three sizes exist
    case broken         // server says broken
    case ameDefect      // AME (HEVC codec pack) missing -> can never be generated by NAS
    case unknown
}

/// One folder from the NAS tree, including folders that hold no media.
public struct FolderEntry: Identifiable, Codable {
    public let id: Int
    public let name: String
    public let path: String

    public init(id: Int, name: String, path: String) {
        self.id = id
        self.name = name
        self.path = path
    }
}

/// Extensions ImageIO can open. Shared by the scanner (to tell a small photo
/// from a broken video) and the engine (to route decoding).
public enum ImageExtensions {
    public static let all: Set<String> = [
        "heic", "heif", "jpg", "jpeg", "png", "dng", "tif", "tiff", "gif", "webp",
        "bmp", "cr2", "cr3", "crw", "nef", "nrw", "arw", "srf", "sr2", "raf",
        "orf", "rw2", "pef", "srw", "raw", "x3f", "3fr", "erf", "mef", "mos", "iiq",
    ]
}

public struct PhotoItem: Codable {
    public let id: Int
    public let filename: String
    public let type: String
    public let bytes: Int
    public let folderId: Int
    public let folderPath: String
    public var state: PreviewState
    public let codec: String?
    public let width: Int?
    public let height: Int?
    public let cacheKey: String?
    /// Number of entries in `video_convert`; 0 means the NAS has no converted copy.
    public let convertedVariants: Int
    /// Per-size server verdict, e.g. ["sm": "ready", "m": "ready", "xl": "ame_defect"].
    public var sizeStates: [String: String]

    /// How many of the three preview sizes the NAS actually has.
    /// A 0-byte file cannot be decoded; it is its own category, not "missing".
    public var isZeroByte: Bool { bytes == 0 }

    /// Names that ImageIO can open. Used to decide what "too small to contain
    /// anything" means: a 100 KB JPEG is a normal photo, a 100 KB video is not.
    public var isImageFile: Bool {
        ImageExtensions.all.contains((filename as NSString).pathExtension.lowercased())
    }

    /// Files that cannot hold usable media at all: empty, or a video clip that
    /// is smaller than a single frame's worth of data.
    public var isInvalid: Bool {
        bytes == 0 || (!isImageFile && bytes < 512 * 1024)
    }

    /// Only `ready` means the three sizes actually exist. Verified against the
    /// thumbnail endpoint: `ameDefect` items return HTTP 404, so they are work.
    public var hasThumbnails: Bool {
        state == .ready
    }

    public init(id: Int, filename: String, type: String = "photo", bytes: Int,
                folderId: Int, folderPath: String, state: PreviewState = .unknown,
                codec: String? = nil, width: Int? = nil, height: Int? = nil,
                cacheKey: String? = nil, convertedVariants: Int = 0,
                sizeStates: [String: String] = [:]) {
        self.id = id
        self.filename = filename
        self.type = type
        self.bytes = bytes
        self.folderId = folderId
        self.folderPath = folderPath
        self.state = state
        self.codec = codec
        self.width = width
        self.height = height
        self.cacheKey = cacheKey
        self.convertedVariants = convertedVariants
        self.sizeStates = sizeStates
    }

    public var readySizeCount: Int {
        ["sm", "m", "xl"].filter { sizeStates[$0] == "ready" }.count
    }
}

/// Read-only enumeration of the Synology Photos shared space.
public final class Scanner {
    private let client: NASClient
    private let pageSize = 200

    public init(client: NASClient) { self.client = client }

    private func int(_ any: Any?) -> Int? {
        if let i = any as? Int { return i }
        if let n = any as? NSNumber { return n.intValue }
        if let s = any as? String { return Int(s) }
        return nil
    }

    public func childFolders(of id: Int) throws -> [(id: Int, name: String)] {
        var out: [(Int, String)] = []
        var offset = 0
        while true {
            let resp = try client.call(
                api: "SYNO.FotoTeam.Browse.Folder",
                version: "2",
                method: "list",
                params: ["id": String(id),
                         "offset": String(offset),
                         "limit": String(pageSize)]
            )
            let list = (resp["data"] as? [String: Any])?["list"] as? [[String: Any]] ?? []
            for f in list {
                guard let fid = int(f["id"]) else { continue }
                out.append((fid, f["name"] as? String ?? "?"))
            }
            offset += list.count
            if list.count < pageSize { break }
        }
        return out
    }

    private func rawItems(folderId: Int, onPage: ((Int) -> Void)? = nil) throws -> [[String: Any]] {
        // The web client uses Browse.Item v7. `video_convert_status` must NOT be
        // requested (the server rejects it with 120) — it is returned anyway and
        // is read from the response.
        let additional = #"["thumbnail","video_meta","video_convert","resolution"]"#
        var out: [[String: Any]] = []
        var offset = 0
        while true {
            let resp = try client.call(
                api: "SYNO.FotoTeam.Browse.Item",
                version: "7",
                method: "list",
                params: ["folder_id": String(folderId),
                         "offset": String(offset),
                         "limit": String(pageSize),
                         "additional": additional]
            )
            let list = (resp["data"] as? [String: Any])?["list"] as? [[String: Any]] ?? []
            out.append(contentsOf: list)
            offset += list.count
            onPage?(offset)
            if list.count < pageSize { break }
        }
        return out
    }

    /// Pure classification of one item's `additional` block. Exposed so the
    /// decision can be unit-tested without a NAS.
    public static func classifyAdditional(_ additional: [String: Any]) -> (PreviewState, String?, Int) {
        let thumb = additional["thumbnail"] as? [String: Any] ?? [:]
        let sizes = ["sm", "m", "xl"].compactMap { thumb[$0] as? String }
        let converted = (additional["video_convert"] as? [Any])?.count ?? 0
        let meta = additional["video_meta"] as? [String: Any] ?? [:]

        // video_convert_status mirrors the thumbnail verdict (e.g. "ame_defect"),
        // so either signal marks the item as ungeneratable by the NAS.
        let convertStatus = additional["video_convert_status"] as? String
        let state: PreviewState
        if sizes.count == 3 && sizes.allSatisfy({ $0 == "ready" }) {
            state = .ready
        } else if sizes.contains("ame_defect") || convertStatus == "ame_defect" {
            state = .ameDefect
        } else if sizes.contains("broken") {
            state = .broken
        } else {
            state = .unknown
        }
        return (state, meta["video_codec"] as? String, converted)
    }

    private func toItem(_ raw: [String: Any], folderId: Int, path: String) -> PhotoItem? {
        guard let id = int(raw["id"]) else { return nil }
        let additional = raw["additional"] as? [String: Any] ?? [:]
        let (state, codec, converted) = Self.classifyAdditional(additional)
        let thumb = additional["thumbnail"] as? [String: Any] ?? [:]
        let meta = additional["video_meta"] as? [String: Any] ?? [:]
        return PhotoItem(
            id: id,
            filename: raw["filename"] as? String ?? "?",
            type: raw["type"] as? String ?? "?",
            bytes: int(raw["filesize"]) ?? 0,
            folderId: folderId,
            folderPath: path,
            state: state,
            codec: codec,
            width: int(meta["resolution_x"]),
            height: int(meta["resolution_y"]),
            cacheKey: thumb["cache_key"] as? String,
            convertedVariants: converted,
            sizeStates: ["sm": thumb["sm"] as? String ?? "?",
                         "m": thumb["m"] as? String ?? "?",
                         "xl": thumb["xl"] as? String ?? "?"]
        )
    }

    /// Walks the whole folder tree from the NAS, so empty folders and levels
    /// deeper than the media are visible too. Read-only.
    public func scanFolders(progress: ((String) -> Void)? = nil) throws -> [FolderEntry] {
        var out: [FolderEntry] = []
        func walk(_ parent: Int, _ prefix: String, depth: Int) throws {
            guard depth < 12 else { return }
            for (fid, name) in try childFolders(of: parent) {
                // The NAS reports `name` as a path relative to the root
                // ("2025/2025-09-trip/…"), not a leaf name.
                let relative = name.hasPrefix("/") ? String(name.dropFirst()) : name
                let path = "/" + relative
                let leaf = relative.split(separator: "/").last.map(String.init) ?? relative
                out.append(FolderEntry(id: fid, name: leaf, path: path))
                progress?(path)
                try walk(fid, path, depth: depth + 1)
            }
        }
        try walk(0, "", depth: 0)
        return out
    }

    /// Timestamp of the newest item in the library. One request: used to decide
    /// whether a refresh scan is needed at all.
    public func newestItemTime() -> Int? {
        let resp = try? client.call(api: "SYNO.FotoTeam.Browse.Item",
                                    version: "7",
                                    method: "list",
                                    params: ["folder_id": "0",
                                             "offset": "0",
                                             "limit": "1",
                                             "sort_by": "takentime",
                                             "sort_direction": "desc"])
        let list = (resp?["data"] as? [String: Any])?["list"] as? [[String: Any]] ?? []
        return list.first?["time"] as? Int
    }

    /// Immediate children of the root — one request, used to let the user pick
    /// which folders to scan instead of walking the whole library.
    public func rootFolders() throws -> [FolderEntry] {
        try childFolders(of: 0).map { id, name in
            let rel = name.hasPrefix("/") ? String(name.dropFirst()) : name
            let trimmed = rel.hasSuffix("/") ? String(rel.dropLast()) : rel
            let leaf = trimmed.split(separator: "/").last.map(String.init) ?? trimmed
            return FolderEntry(id: id, name: leaf, path: "/" + trimmed)
        }
    }

    /// One traversal that discovers the folder tree and lists items in
    /// parallel, reporting batches as they arrive so the UI fills in live.
    public func scanIncremental(subtrees: [(id: Int, path: String)]? = nil,
                                workers: Int = 10,
                                onDiscovery: ((Int) -> Void)? = nil,
                                onFolders: (([FolderEntry]) -> Void)? = nil,
                                onBatch: (([PhotoItem]) -> Void)? = nil,
                                onProgress: ((Int, Int) -> Void)? = nil) throws -> [PhotoItem] {
        // 1) Folder tree first: cheap, and it tells us how much work is coming.
        var folders: [(id: Int, path: String)] = []
        var entries: [FolderEntry] = []
        var stack: [(Int, String)] = subtrees?.map { ($0.id, $0.path) } ?? [(0, "/")]
        var guardCount = 0
        while let (fid, path) = stack.popLast() {
            guardCount += 1
            guard guardCount < 20_000 else { break }
            for child in try childFolders(of: fid) {
                let name = child.name.hasPrefix("/") ? child.name : path + child.name
                let normalized = name.hasSuffix("/") ? name : name + "/"
                stack.append((child.id, normalized))
                let trimmed = normalized.hasSuffix("/") ? String(normalized.dropLast()) : normalized
                let leaf = trimmed.split(separator: "/").last.map(String.init) ?? trimmed
                entries.append(FolderEntry(id: child.id, name: leaf, path: trimmed))
                folders.append((child.id, trimmed))
                if entries.count % 25 == 0 { onDiscovery?(entries.count) }
            }
        }
        onFolders?(entries)

        // 2) Items per folder, a few folders at a time.
        let lock = NSLock()
        var all: [PhotoItem] = []
        var finished = 0
        let group = DispatchGroup()
        let queue = DispatchQueue(label: "sia.scan", qos: .userInitiated, attributes: .concurrent)
        let sem = DispatchSemaphore(value: max(1, min(workers, 12)))
        for folder in folders {
            group.enter()
            queue.async {
                sem.wait()
                defer { sem.signal(); group.leave() }
                let raws = (try? self.rawItems(folderId: folder.id)) ?? []
                var local: [PhotoItem] = []
                for raw in raws {
                    if let item = self.toItem(raw, folderId: folder.id, path: folder.path) {
                        local.append(item)
                    }
                }
                if !local.isEmpty { onBatch?(local) }
                lock.lock()
                all.append(contentsOf: local)
                finished += 1
                let total = all.count
                let done = finished
                lock.unlock()
                onProgress?(done, total)
            }
        }
        group.wait()
        return all
    }

    /// Walks the whole granted tree. Read-only: only Browse.* calls are made.
    public func scanAll(progress: ((String, Int) -> Void)? = nil) throws -> [PhotoItem] {
        var items: [PhotoItem] = []
        var stack: [(Int, String)] = [(0, "/")]
        var visited = 0
        while let (fid, path) = stack.popLast() {
            for child in try childFolders(of: fid) {
                let name = child.name.hasPrefix("/") ? child.name : path + child.name
                let normalized = name.hasSuffix("/") ? name : name + "/"
                stack.append((child.id, normalized))
            }
            // Folder 0 is the virtual root: it has no items and the API rejects
            // Browse.Item on it with 642, so only real folders are listed.
            if fid != 0 {
                let raws = (try? rawItems(folderId: fid)) ?? []
                for raw in raws {
                    if let item = toItem(raw, folderId: fid, path: path) { items.append(item) }
                }
            }
            visited += 1
            progress?(path, items.count)
            if visited > 5000 { break }
        }
        return items
    }
}
